# ---------------------------------------------------------------------------
# 数学公式保护:在 markdown 转换前把公式替换成占位符,转换后再还原,
# 避免 $x_i^2$ 中的下划线/星号等被 markdown 误解析。
# ---------------------------------------------------------------------------
FENCE_RE = re.compile(r"(```.*?```|~~~.*?~~~)", re.S)
INLINE_CODE_RE = re.compile(r"`[^`\n]+`")
DISPLAY_MATH_RE = re.compile(r"\$\$(.+?)\$\$", re.S)
INLINE_MATH_RE = re.compile(r"(?<![\\$\w])\$(?!\s)(.+?)(?<!\s)\$(?!\w)")
PAREN_MATH_RE = re.compile(r"\\\((.+?)\\\)", re.S)
BRACKET_MATH_RE = re.compile(r"\\\[(.+?)\\\]", re.S)


def extract_math(text: str):
    """把代码块/行内代码/公式全部替换为占位符,返回 (处理后文本, 占位符表)。"""
    store: dict[str, str] = {}

    def stash(raw: str) -> str:
        key = f"ZQXMATH{len(store)}XZ"
        store[key] = raw
        return key

    parts = FENCE_RE.split(text)
    processed = []
    for part in parts:
        if not part:
            continue
        # 代码块原样保护
        if part.startswith("```") or part.startswith("~~~"):
            processed.append(part)
            continue
        # 行内代码保护
        part = INLINE_CODE_RE.sub(lambda m: stash(m.group(0)), part)
        # 公式保护(display 优先,避免 $$ 被当成两个 $)
        part = DISPLAY_MATH_RE.sub(lambda m: stash(m.group(0)), part)
        part = PAREN_MATH_RE.sub(lambda m: stash(m.group(0)), part)
        part = BRACKET_MATH_RE.sub(lambda m: stash(m.group(0)), part)
        part = INLINE_MATH_RE.sub(lambda m: stash(m.group(0)), part)
        processed.append(part)

    return "".join(processed), store


def restore_math(html_text: str, store: dict[str, str]) -> str:
    """把占位符还原为 HTML 转义后的公式原文,交给前端 KaTeX 渲染。"""
    for key, raw in store.items():
        html_text = html_text.replace(key, html.escape(raw))
    return html_text


# ---------------------------------------------------------------------------
# 文章元信息
# ---------------------------------------------------------------------------
H1_RE = re.compile(r"^#\s+(.+?)\s*#*\s*$", re.M)


def article_meta(md_text: str, md_path: Path):
    """提取标题(首个 H1,否则用文件名)与摘要(首个非标题段落)。"""
    m = H1_RE.search(md_text)
    title = m.group(1).strip() if m else md_path.stem
    # 标题已用于 section-title,正文里去掉首个 H1 避免重复
    if m:
        md_text = md_text[: m.start()] + md_text[m.end():]

    desc = ""
    for block in re.split(r"\n\s*\n", md_text):
        block = block.strip()
        if block and not block.startswith(("#", "```", "~~~", "!", "|", ">")):
            desc = re.sub(r"[*_`$\[\]]", "", block)[:120]
            break
    if not desc:
        desc = f"lordrebel 的文章 — {title}"

    date_str = datetime.fromtimestamp(md_path.stat().st_mtime).strftime("%Y.%m.%d")
    return title, desc, date_str, md_text


