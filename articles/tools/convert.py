def ensure_article_css() -> None:
    """首次运行时生成 css/article.css(已存在则不覆盖,便于手动定制)。"""
    if not ARTICLE_CSS.exists():
        ARTICLE_CSS.parent.mkdir(parents=True, exist_ok=True)
        ARTICLE_CSS.write_text(ARTICLE_CSS_TEXT, encoding="utf-8")
        print(f"[css] 生成样式文件: {ARTICLE_CSS.relative_to(ROOT)}")


def pick_random_bg() -> str:
    """从 images/resource 随机挑一张背景图,返回相对 articles/htmls 的路径。"""
    images = [p for p in RES_DIR.iterdir() if p.suffix.lower() in IMG_EXTS] if RES_DIR.is_dir() else []
    if not images:
        return ""
    chosen = random.choice(images)
    rel = chosen.relative_to(ROOT).as_posix()
    print(f"[bg]  随机背景: {rel}")
    return f"../../{rel}"


def convert_file(md_path: Path, out_path: Path) -> None:
    md_text = md_path.read_text(encoding="utf-8")
    title, desc, date_str, body = article_meta(md_text, md_path)

    protected, store = extract_math(body)
    content_html = markdown.markdown(
        protected,
        extensions=["extra", "toc", "sane_lists"],  # extra 含 tables / fenced_code
        output_format="html5",
    )
    content_html = restore_math(content_html, store)

    # 缩进正文,保持生成文件排版整洁
    content_html = "\n".join("      " + line if line.strip() else "" for line in content_html.splitlines())

    page = (
        TEMPLATE.replace("{{DESC}}", html.escape(desc))
        .replace("{{TITLE}}", html.escape(title))
        .replace("{{DATE}}", date_str)
        .replace("{{BG_IMG}}", pick_random_bg())
        .replace("{{CONTENT}}", content_html)
    )

    out_path.write_text(page, encoding="utf-8")
    print(f"[ok]  {md_path.relative_to(ROOT)}  ->  {out_path.relative_to(ROOT)}")
    return {"title": title, "file": out_path.name, "date": date_str}


def write_articles_js(metas: list[dict], out_dir: Path) -> None:
    """生成文章清单 articles/htmls/articles.js,供主页导航栏「文章」下拉列表加载。

    GitHub Pages 是纯静态站点,无法列目录,因此用 JS 变量清单代替:
    主页通过 <script src="articles/htmls/articles.js"> 加载全局变量 ARTICLES。
    """
    items = ",\n".join(
        "  {{ \"title\": {title}, \"file\": {file}, \"date\": {date} }}".format(
            title=json.dumps(m["title"], ensure_ascii=False),
            file=json.dumps(m["file"], ensure_ascii=False),
            date=json.dumps(m["date"], ensure_ascii=False),
        )
        for m in metas
    )
    js = (
        "/* 文章清单 — 由 articles/tools/convert.py 自动生成,勿手动修改 */\n"
        "var ARTICLES = [\n" + items + "\n];\n"
    )
    manifest = out_dir / MANIFEST_JS
    manifest.write_text(js, encoding="utf-8")
    print(f"[js]  生成文章清单: {manifest.relative_to(ROOT)} ({len(metas)} 篇)")


def main() -> None:
    parser = argparse.ArgumentParser(description="Markdown 文章 -> 赛博朋克风格 HTML")
    parser.add_argument("--md-dir", type=Path, default=MD_DIR, help="Markdown 源目录")
    parser.add_argument("--out-dir", type=Path, default=OUT_DIR, help="HTML 输出目录")
    parser.add_argument("--seed", type=int, default=None, help="随机背景的随机种子(便于复现)")
    args = parser.parse_args()

    if args.seed is not None:
        random.seed(args.seed)

    md_dir: Path = args.md_dir
    out_dir: Path = args.out_dir
    if not md_dir.is_dir():
        sys.exit(f"源目录不存在: {md_dir}")

    md_files = sorted(md_dir.glob("*.md"))
    if not md_files:
        sys.exit(f"{md_dir} 下没有找到 .md 文件")

    out_dir.mkdir(parents=True, exist_ok=True)
    ensure_article_css()

    metas = []
    for md_path in md_files:
        metas.append(convert_file(md_path, out_dir / (md_path.stem + ".html")))

    # 按日期倒序排列,最新文章在前
    metas.sort(key=lambda m: m["date"], reverse=True)
    write_articles_js(metas, out_dir)

    print(f"\n完成: 共转换 {len(md_files)} 篇文章 -> {out_dir}")


if __name__ == "__main__":
    main()
